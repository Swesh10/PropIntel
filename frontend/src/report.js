import { jsPDF } from "jspdf";

function inr(n) {
  if (n === null || n === undefined) return "-";
  if (n >= 10000000) return `Rs ${(n / 10000000).toFixed(2)} Cr`;
  if (n >= 100000) return `Rs ${(n / 100000).toFixed(1)} Lakh`;
  return `Rs ${Math.round(n).toLocaleString("en-IN")}`;
}

export const Report = {
  /**
   * Generates and downloads a PDF summarising the user's recommended
   * properties and the catalog's current listing snapshot.
   */
  generatePDF({ prefs, results = [], trends, city }) {
    const doc = new jsPDF({ unit: "pt", format: "a4" });
    const margin = 48;
    let y = margin;

    // Header
    doc.setFillColor(15, 23, 42);
    doc.rect(0, 0, 595, 90, "F");
    doc.setTextColor(255, 255, 255);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(20);
    doc.text("PropIntel", margin, 44);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(11);
    doc.text("Maharashtra AI-Powered Property Insight Report", margin, 64);

    y = 118;
    doc.setTextColor(15, 23, 42);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(13);
    doc.text(
      `Preferences: ${city}, ${prefs.bhk} BHK, budget ${inr(prefs.budget_min)}–${inr(prefs.budget_max)}`,
      margin,
      y,
    );
    y += 26;

    doc.setFont("helvetica", "bold");
    doc.setFontSize(12);
    doc.text("Recommended Properties", margin, y);
    y += 18;

    doc.setFont("helvetica", "normal");
    doc.setFontSize(10);
    doc.text(
      "Listed prices are source listing asking prices, not confirmed sale prices. AI estimates exclude each listing from its own training fold.",
      margin,
      y,
    );
    y += 16;
    results.slice(0, 8).forEach((r, idx) => {
      if (y > 760) {
        doc.addPage();
        y = margin;
      }
      const line1 = `${idx + 1}. ${r.bhk} BHK ${r.property_type} - ${r.locality}, ${r.city} (${Number(r.area_sqft).toLocaleString("en-IN")} sq.ft)`;
      const listedPrice = r.listed_price;
      const priceDifference = Number.isFinite(Number(listedPrice)) && Number.isFinite(Number(r.fair_price))
        ? Math.abs(Number(listedPrice) - Number(r.fair_price))
        : null;
      const differencePercent = Number.isFinite(Number(r.price_difference_pct))
        ? `${Number(r.price_difference_pct).toFixed(1)}%`
        : "not available";
      const line2 = `   Listed: ${inr(listedPrice)}   AI estimate: ${inr(r.fair_price)}   Difference: ${inr(priceDifference)} (${differencePercent})   Price agreement: ${r.price_agreement || "unbenchmarked"}   Match score: ${r.match_score}%   Source marked verified: ${r.source_verified ? "yes" : "no"}`;
      doc.text(line1, margin, y);
      y += 14;
      const wrappedLine = doc.splitTextToSize(line2, 500);
      doc.text(wrappedLine, margin, y);
      y += wrappedLine.length * 12 + 8;
    });

    if (trends) {
      y += 10;
      if (y > 720) {
        doc.addPage();
        y = margin;
      }
      doc.setFont("helvetica", "bold");
      doc.setFontSize(12);
      doc.text(`${city || "All zones"} - Current Listing Snapshot`, margin, y);
      y += 18;
      doc.setFont("helvetica", "normal");
      doc.setFontSize(10);
      doc.text(`Listings in catalog: ${Number(trends.total_properties || 0).toLocaleString("en-IN")}`, margin, y);
      y += 14;
      doc.text(
        `Average asking price per sq.ft: Rs ${Math.round(Number(trends.average_price_per_sqft || 0)).toLocaleString("en-IN")}`,
        margin,
        y,
      );
      y += 14;
      const distribution = Object.entries(trends.bhk_distribution || {})
        .map(([bhk, count]) => `${bhk} BHK: ${Number(count).toLocaleString("en-IN")}`)
        .join("   ");
      if (distribution) {
        const wrapped = doc.splitTextToSize(distribution, 500);
        doc.text(wrapped, margin, y);
        y += wrapped.length * 14;
      }
      y += 8;
      doc.setFontSize(9);
      doc.text("Descriptive statistics from current cleaned listings; not a future price prediction.", margin, y);
    }

    doc.setFontSize(8);
    doc.setTextColor(148, 163, 184);
    doc.text(
      "Generated by PropIntel. Estimates are AI-generated guidance, not a formal valuation.",
      margin,
      815
    );

    doc.save(`PropIntel-Report-${city}-${new Date().toISOString().slice(0, 10)}.pdf`);
  },
};
